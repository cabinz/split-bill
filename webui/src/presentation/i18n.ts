function interpolate(message: string, params: Params): string {
  return message.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`))
}

export function t(key: string, params: Params = {}): string {
  const messages = locale.value === 'zh-CN' ? zh : en
  return interpolate(messages[key] ?? en[key] ?? key, params)
}

/** Switch language and remember the choice. What the picker calls. */
export function setLocale(next: Locale): void {
  applyLocale(next)
  try {
    localStorage.setItem(STORAGE_KEY, next)
  } catch {
    // Storage can be disabled; the in-memory choice still works for this report.
  }
}

/**
 * Switch language without remembering it.
 *
 * What the print preview window calls. It renders a `PrintInput` frozen in whatever
 * language the report was in when the button was pressed, which is not a preference the
 * user expressed -- writing it to storage would let printing a report silently change the
 * language of the next session.
 */
export function applyLocale(next: Locale): void {
  locale.value = next
  // Guarded so this module can be imported outside a browser -- the unit tests run under
  // `node --test`, where there is no document and the two side effects below are simply
  // not applicable. The translations themselves need nothing from the DOM.
  if (typeof document === 'undefined') return
  document.documentElement.lang = next
  const description = document.querySelector<HTMLMetaElement>('meta[name="description"]')
  if (description) description.content = t('app.tagline')
}

export function useI18n() {
  return {
    locale,
    isZh: computed(() => locale.value === 'zh-CN'),
    setLocale,
    t,
  }
}

export function translateBackendMessage(message: string): string {
  if (locale.value !== 'zh-CN') return message
  if (message === 'No exchange rates provided. Run in the currency-agnostic way.') {
    return t('backend.noRates')
  }
  if (message === 'the bill has validation errors') {
    return t('backend.validationErrors')
  }
  if (message === 'Name separator cannot be empty') {
    return t('backend.emptySeparator')
  }
  const separator = message.match(
    /^This cell may use '(.+)' as the name separator instead of the selected '(.+)'$/,
  )
  if (separator) {
    return t('backend.separatorMismatch', {
      found: separator[1] ?? '',
      selected: separator[2] ?? '',
    })
  }
  return message
}

